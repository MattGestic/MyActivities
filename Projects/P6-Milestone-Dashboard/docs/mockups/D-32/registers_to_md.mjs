// Writes the D-32 field and build registers as Markdown from the FIELDS, BUILD and CLARITY
// arrays in shell-options.html. The HTML is the single source: edit the arrays there, then run
//   node docs/mockups/D-32/registers_to_md.mjs
// from Projects/P6-Milestone-Dashboard. Output: docs/decisions/D-32-field-register.md and
// docs/decisions/D-32-build-register.md. Never hand-edit the outputs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, 'shell-options.html'), 'utf8');
const grab = name => {
  const m = html.match(new RegExp(`const ${name}=(\\[[\\s\\S]*?\\n\\]);`));
  if (!m) throw new Error(`array ${name} not found`);
  return Function(`return ${m[1]}`)();
};
const FIELDS = grab('FIELDS'), BUILD = grab('BUILD'), CLARITY = grab('CLARITY');
const VLBL = { keep: 'Keep', move: 'Move', hide: 'Hidden by default', diff: 'Shown differently', omit: 'Omit', new: 'New, derived' };
const cell = s => String(s).replace(/\|/g, '\\|');
const out = join(here, '..', '..', 'decisions');
const head = (title, lead) => `<!-- Generated by docs/mockups/D-32/registers_to_md.mjs from shell-options.html. Do not edit by hand. -->\n# ${title}\n\n${lead}\n\n`;

writeFileSync(join(out, 'D-32-field-register.md'),
  head('D-32 field register',
    'Part of [D-32](D-32-shell-navigation.md). One row per field the milestone pane or board shows, with what the redesign does with it and why.\n\n' +
    '**Rule: nothing is removed from import, storage or export.** "Hidden by default" and "Omit" are display choices only. Every alias in `INGEST_CONFIG.headerAliases` stays. "New, derived" means the value is computed from data the app already holds unless the last column names a build item.') +
  '| Field | Source | Shown today | In redesign | Where | Why | Backend and import |\n|---|---|---|---|---|---|---|\n' +
  FIELDS.map(f => `| ${cell(f[0])} | ${cell(f[1])} | ${cell(f[2])} | **${VLBL[f[3]]}** | ${cell(f[4])} | ${cell(f[5])} | ${cell(f[6])} |`).join('\n') + '\n');

writeFileSync(join(out, 'D-32-build-register.md'),
  head('D-32 build register',
    'Part of [D-32](D-32-shell-navigation.md). Functions the round-2 mockup shows that the app does not have yet. Frames tag them **Build**. Sizes are first-pass estimates (S, M, L) [CONFIRM after spike].') +
  '| ID | Function | Today | To build | Builds on | Size |\n|---|---|---|---|---|---|\n' +
  BUILD.map(b => `| ${b.map(cell).join(' | ')} |`).join('\n') +
  '\n\n## Clarity fixes in round 2\n\n| What was unclear | Fix |\n|---|---|\n' +
  CLARITY.map(c => `| ${cell(c[0])} | ${cell(c[1])} |`).join('\n') + '\n');
console.log(`wrote ${FIELDS.length} fields, ${BUILD.length} build items, ${CLARITY.length} clarity fixes`);
